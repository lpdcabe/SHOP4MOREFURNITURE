import { useEffect, useMemo, useState } from 'react';
import Layout from '../components/Layout.jsx';
import ChartCanvas from '../components/ChartCanvas.jsx';
import { api, formatPeso } from '../services/api.js';

export default function ReportsPage() {
  const [dash, setDash] = useState(null);
  const [error, setError] = useState('');

  useEffect(() => {
    api
      .dashboard()
      .then(setDash)
      .catch((err) => setError(err.message));
  }, []);

  const summary = dash?.summary || {
    totalStock: 0,
    totalStockInQty: 0,
    totalStockOutQty: 0,
    totalSalesAmount: 0,
    inStockCount: 0,
    lowStockCount: 0,
    outOfStockCount: 0
  };

  const barData = useMemo(
    () => ({
      labels: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul'],
      datasets: [
        {
          label: 'Stock In',
          backgroundColor: '#6B1020',
          data: [120, 150, 170, 180, 210, 240, 230]
        },
        {
          label: 'Stock Out',
          backgroundColor: '#d6a2ae',
          data: [80, 95, 110, 130, 160, 170, 180]
        }
      ]
    }),
    []
  );

  const statusData = useMemo(
    () => ({
      labels: ['Available', 'Low Stock', 'Out of Stock'],
      datasets: [
        {
          data: [
            summary.inStockCount || 0,
            summary.lowStockCount || 0,
            summary.outOfStockCount || 0
          ],
          backgroundColor: ['#6B1020', '#ffc107', '#dc3545']
        }
      ]
    }),
    [summary]
  );

  const exportCsv = () => {
    const products = dash?.products || [];
    const header = ['Code', 'Name', 'Category', 'Supplier', 'Stock', 'Price'];
    const rows = products.map((p) => [
      p.code,
      `"${p.name}"`,
      p.category,
      `"${p.supplier_name}"`,
      p.stock,
      p.price
    ]);
    const csv = [header.join(','), ...rows.map((r) => r.join(','))].join('\n');
    const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'shop4more-report.csv';
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <Layout title="Reports & Analytics">
      {error && <div className="alert alert-warning">{error}</div>}

      <div className="row mt-2 g-3 g-md-4">
        <div className="col-lg-3 col-6">
          <div className="card dashboard-card">
            <i className="fas fa-box" />
            <h3>{summary.totalStock}</h3>
            <p>Total Inventory</p>
          </div>
        </div>
        <div className="col-lg-3 col-6">
          <div className="card dashboard-card">
            <i className="fas fa-arrow-down" />
            <h3>{summary.totalStockInQty}</h3>
            <p>Stock In</p>
          </div>
        </div>
        <div className="col-lg-3 col-6">
          <div className="card dashboard-card">
            <i className="fas fa-arrow-up" />
            <h3>{summary.totalStockOutQty}</h3>
            <p>Stock Out</p>
          </div>
        </div>
        <div className="col-lg-3 col-6">
          <div className="card dashboard-card">
            <i className="fas fa-coins" />
            <h3>{formatPeso(summary.totalSalesAmount)}</h3>
            <p>Total Sales</p>
          </div>
        </div>
      </div>

      <div className="row mt-4 g-4">
        <div className="col-lg-8">
          <div className="card p-4">
            <h5>Monthly Inventory Movement</h5>
            <ChartCanvas type="bar" data={barData} options={{ responsive: true }} />
          </div>
        </div>
        <div className="col-lg-4">
          <div className="card p-4">
            <h5>Inventory Status</h5>
            <ChartCanvas type="doughnut" data={statusData} options={{ responsive: true }} />
          </div>
        </div>
      </div>

      <div className="card mt-4 p-4">
        <div className="d-flex justify-content-between align-items-center">
          <h4 className="mb-0">Generated Reports</h4>
          <div className="d-flex gap-2">
            <button className="btn btn-success" onClick={exportCsv}>
              <i className="fas fa-file-excel me-2" />
              Export CSV
            </button>
            <button className="btn btn-danger" onClick={() => window.print()}>
              <i className="fas fa-file-pdf me-2" />
              Print / PDF
            </button>
          </div>
        </div>

        <table className="table table-hover mt-4">
          <thead>
            <tr>
              <th>Report</th>
              <th>Generated By</th>
              <th>Date</th>
              <th>Status</th>
            </tr>
          </thead>
          <tbody>
            <tr>
              <td>Monthly Inventory Report</td>
              <td>Administrator</td>
              <td>{new Date().toLocaleDateString()}</td>
              <td>
                <span className="badge bg-success">Ready</span>
              </td>
            </tr>
            <tr>
              <td>Sales Report</td>
              <td>Administrator</td>
              <td>{new Date().toLocaleDateString()}</td>
              <td>
                <span className="badge bg-success">Ready</span>
              </td>
            </tr>
            <tr>
              <td>Low Stock Report</td>
              <td>Administrator</td>
              <td>{new Date().toLocaleDateString()}</td>
              <td>
                <span className="badge bg-success">Ready</span>
              </td>
            </tr>
            <tr>
              <td>Supplier Performance</td>
              <td>Administrator</td>
              <td>{new Date().toLocaleDateString()}</td>
              <td>
                <span className="badge bg-success">Ready</span>
              </td>
            </tr>
          </tbody>
        </table>
      </div>
    </Layout>
  );
}
